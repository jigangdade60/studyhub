class GroupMessage < ApplicationRecord
  # =========================
  # アソシエーション
  # =========================

  # グループメッセージは、必ず1つのグループに紐づく
  #
  # 例：
  # 「Rails勉強会」というグループに投稿されたメッセージであれば、
  # そのメッセージは group_id を通して Group モデルと関連する
  #
  # これにより、
  # group_message.group
  # のように書くことで、そのメッセージが投稿されたグループを取得できる
  belongs_to :group

  # グループメッセージは、必ず1人のユーザーに紐づく
  #
  # 例：
  # 「田中さんがグループに投稿したメッセージ」であれば、
  # そのメッセージは user_id を通して User モデルと関連する
  #
  # これにより、
  # group_message.user
  # のように書くことで、そのメッセージを投稿したユーザーを取得できる
  belongs_to :user

  # =========================
  # バリデーション
  # =========================

  # content はグループメッセージの本文を表すカラム
  #
  # presence: true によって、空のメッセージを投稿できないようにしている
  # これがないと、何も入力していない空白のメッセージが保存されてしまう可能性がある
  #
  # length: { maximum: 500 } によって、本文を500文字以内に制限している
  # 長すぎる文章を制限することで、画面表示の崩れやDBへの不要な負荷を防ぐ目的がある
  validates :content, presence: true, length: { maximum: 500 }
end
