class Session < ApplicationRecord
  # =========================
  # セッション管理モデル
  # =========================
  #
  # Sessionモデルは、
  # 「現在ログインしている状態」をDBで管理するためのモデル。
  #
  # このアプリでは、ログイン対象が
  # ・一般ユーザー（User）
  # ・管理者（Admin）
  # の2種類あるため、Sessionモデルはそのどちらかに紐づく設計にしている。

  # =========================
  # 一般ユーザーとの関連
  # =========================

  # 1つのセッションは、一般ユーザーに紐づくことがある
  #
  # 例：
  # 一般ユーザーがログインした場合、
  # sessionsテーブルの user_id にログイン中ユーザーのIDが入る。
  #
  # optional: true を指定している理由：
  # このSessionは「一般ユーザー専用」ではなく、
  # 管理者ログインにも使うため。
  #
  # 管理者がログインしている場合は user_id が nil になる可能性がある。
  # そのため、user_id が必須だと管理者用セッションを作成できなくなる。
  belongs_to :user, optional: true

  # =========================
  # 管理者との関連
  # =========================

  # 1つのセッションは、管理者に紐づくことがある
  #
  # 例：
  # 管理者がログインした場合、
  # sessionsテーブルの admin_id にログイン中管理者のIDが入る。
  #
  # optional: true を指定している理由：
  # 一般ユーザーがログインしている場合は admin_id が nil になるため。
  #
  # admin_id を必須にしてしまうと、
  # 一般ユーザー用のセッションを作成できなくなる。
  belongs_to :admin, optional: true

  # =========================
  # この設計のポイント
  # =========================
  #
  # Sessionは、UserまたはAdminのどちらか一方に紐づく想定。
  #
  # 一般ユーザーのログイン時：
  #   user_id あり
  #   admin_id nil
  #
  # 管理者のログイン時：
  #   user_id nil
  #   admin_id あり
  #
  # つまり、1つのSessionモデルで
  # 一般ユーザー用ログインと管理者用ログインの両方を管理している。
end